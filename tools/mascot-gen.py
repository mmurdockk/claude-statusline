#!/usr/bin/env python3
# Generate the status line mascot frames: Clawd, the Claude Code mascot.
#
# The pieces below are modelled on the welcome-screen sprite of Claude Code
# (2.1.310), so the mascot matches the one you already know.
# Claude Code assembles Clawd from parts on a 9x3 cell grid:
#   row 0  left arm at col 0-1, eye span from col 2, right arm at col 8
#   row 1  left arm at col 0-1, body "█████" at col 2-6, right arm at col 7-8
#   row 2  feet
# Eye cells are painted on a black ground, so the holes in ▛ / ▟ read as pupils.
# A shut eye ("lid") is the reverse: a black ▂ on a body-coloured ground.
# Anything outside the painted span shows the terminal through, which keeps the
# silhouette edges clean.
#
# Alignment rule: the first printed column of every terminal row must be a
# printable glyph, or the TUI eats the indentation. The status line prints an
# anchor glyph in front of every row, so the art here may start with spaces.
#
# Frames are emitted as shell double-quoted strings referring to colour
# variables the status line sets per render, not as baked-in escapes: the body
# colour tracks gauge pressure, so it cannot be frozen at generation time.
#   $MB  body fg (varies)   $MEF eye fg   $MX  bg off
#   $MBB body bg (varies)   $MEB eye bg   $MZ  reset

TOK = {"fg_B": "${MB}", "fg_E": "${MEF}",
       "bg_B": "${MBB}", "bg_E": "${MEB}", "bg_off": "${MX}", "reset": "${MZ}"}
WIDTH = 9

# ── Parts, from Claude Code ───────────────────────────────────────────────────
ARMS = {  # r1L, r1R, r2L, r2R
    "down":   (" ▐", "",  "▝▜", "█▀"),
    "up":     ("▗▟", "▄", " ▜", "█▘"),
    "one-up": (" ▐", "▄", "▝▜", "█▘"),
}
EYES = {  # spans of (glyphs, is_lid), laid end to end from col 2
    "open":   [("▛███▛█", False)],
    "closed": [("▂", True), ("███", False), ("▂", True), ("█", False)],
    "wink":   [("▛███", False), ("▂", True), ("█", False)],
}
FEET = {
    "both":  " ▝▝   ▝▝ ",
    "left":  " ▝▝      ",
    "right": "      ▝▝ ",
    "none":  "         ",   # ours: airborne
}
# Claude Code also ships glance (eyes left/right) and head-turn poses. They are
# left out: shifting the pupils by a quadrant reads as a twitch, not a look.

# A cell is (glyph, fg, bg); fg/bg in {"B", "E", None}.
def plain(s):
    return [(ch, None if ch == " " else "B", None) for ch in s]

def pose(eyes="open", arms="down", feet="both"):
    r1l, r1r, r2l, r2r = ARMS[arms]
    row0 = plain(r1l)
    for glyphs, lid in EYES[eyes]:
        row0 += [(ch, "E", "B") if lid else (ch, "B", "E") for ch in glyphs]
    row0 += plain(r1r or " ")
    row1 = plain(r2l) + plain("█████") + plain(r2r)
    return [row0, row1, plain(FEET[feet])]

FRAMES = {
    0:  pose(),                                  # stand
    1:  pose(feet="left"),                       # walk: right foot lifted
    3:  pose(arms="one-up", feet="right"),       # walk: left foot lifted, arm swing
    5:  pose(eyes="closed"),                     # blink
    8:  pose(arms="up", feet="none"),            # hop
    10: pose(eyes="closed"),                     # asleep
    12: pose(eyes="wink", arms="up"),            # party: wink
    15: pose(arms="up", feet="left"),            # party: dance
    16: pose(arms="up", feet="right"),           # party: dance
    20: pose(arms="one-up"),                     # ponder: hand to the chin
    21: pose(eyes="closed", arms="one-up"),      # ponder: blink
    22: pose(eyes="wink", arms="one-up"),        # ponder: wink
}

def render(row):
    """One terminal row of cells -> string for printf %b, minimal escapes."""
    out, fg, bg = [], None, None
    for ch, f, b in row:
        if ch == "█":
            b = None            # a full block hides its ground anyway
        if f is None and b is None:
            if fg or bg:
                out.append(TOK["reset"]); fg = bg = None
            out.append(ch); continue
        if b is None and bg is not None:
            out.append(TOK["bg_off"]); bg = None
        if f != fg:
            out.append(TOK["fg_" + f]); fg = f
        if b is not None and b != bg:
            out.append(TOK["bg_" + b]); bg = b
        out.append(ch)
    out.append(TOK["reset"])
    return "".join(out)

for n, rows in FRAMES.items():
    assert len(rows) == 3, n
    for r, row in enumerate(rows):
        assert len(row) == WIDTH, (n, r, len(row))

print("  # generated by tools/mascot-gen.py -- %d frames x 3 rows" % len(FRAMES))
print("  case $frame in")
for n, rows in FRAMES.items():
    if n == 0:
        continue
    print('    %d) m1="%s"; m2="%s"; m3="%s" ;;' % ((n,) + tuple(render(r) for r in rows)))
print('    *) m1="%s"; m2="%s"; m3="%s" ;;   # 0 stand' % tuple(render(r) for r in FRAMES[0]))
print("  esac")
